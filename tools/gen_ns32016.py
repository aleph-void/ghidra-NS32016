def lpr_body(reg, s, src):
    n = SZB[s]
    if reg == "UPSR":
        v = src if s == "B" else f"{src}:1"
        return f"local v:1 = {v};\npsr_load_low(v);"
    if reg == "PSR":
        if s == "B":
            return f"local v:1 = {src};\npsr_load_low(v);"
        v = src if s == "W" else f"{src}:2"
        return f"local v:2 = {v};\npsr_load(v);"
    if reg == "MOD":
        return f"MOD = {src if s == 'W' else (src + ':2' if s == 'D' else 'zext(' + src + ')')};"
    if reg == "USP":
        v = zx(src, s)
        return f"local v:4 = {v};\nif (S == 0) goto <alt>;\nSP = v;\ngoto <done>;\n<alt>\nSPB = v;\n<done>"
    tgt = {"FP": "FP", "SP": "SP", "SB": "SB", "INTBASE": "INTBASE", "DCR": "DCR", "BPC": "BPC", "DSR": "DSR",
           "CAR": "CAR", "CFG": "CFG"}[reg]
    return f"{tgt} = {zx(src, s)};"


def spr_body(reg, s, dst):
    if reg == "UPSR":
        v = "local v:2 = 0;\npsr_pack(v);\n"
        return v + f"{dst} = {('v:1' if s == 'B' else 'zext(v:1)')};"
