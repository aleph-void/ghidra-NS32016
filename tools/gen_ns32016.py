def reglist_tables():
    emit("# --- register lists (SAVE/ENTER push in R0..R7 order, RESTORE/EXIT pop with the bits reversed)")
    for name, kind in (("rlsave", "push"), ("rlenter", "push"), ("rlrest", "pop"), ("rlexit", "pop")):
        for v in range(256):
            if kind == "push":
                regs = [i for i in range(8) if v >> i & 1]
                body = "".join(f"\tSP = SP - 4; *[ram]:4 SP = R{i};\n" for i in regs)
            else:
                regs = [7 - i for i in range(8) if v >> i & 1]
                body = "".join(f"\tR{r} = *[ram]:4 SP; SP = SP + 4;\n" for r in regs)
            disp = "[" + ",".join(f"R{r}" for r in sorted(regs)) + "]" if regs else "[]"
            emit(f'{name}: "{disp}" is rl={v} {{\n{body.rstrip()}\n}}' if body else f'{name}: "{disp}" is rl={v} {{ }}')
    emit()


