def con(mnem, ops, head, gens=(), tail=(), body="", ctx="", gcons=None, priv=False):
    """Emit one top-level constructor.

    mnem  -- mnemonic display text, e.g. 'ADDB' or 'S^cc2^"B"' (a literal first)
    ops   -- operand display text ('' for none)
    head  -- opcode pattern; '{G}' is replaced by the gen-field constraints
    gens  -- ((pos, table), ...) general operands in encoding order
    tail  -- extra pattern elements after the gen operands (each separated by ';')
    body  -- p-code
    ctx   -- extra disassembly-time actions
    gcons -- {pos: constraint} replacing the plain 'g<pos>' field for that operand
    priv  -- privileged instruction: in user mode (PSR.U) it traps instead of executing
    """
    gcons = gcons or {}
    poss = sorted({g[0] for g in gens})
    gf = " & ".join(gcons.get(p, f"g{p}") for p in poss)
    head = head.replace("{G}", (" & " + gf) if gf else "")
    chain = [head]
    names = []
    actions = []
    for p in poss:
        chain.append(f"ix{p}")
        names.append(f"ix{p}")
        actions.append(f"m{p} = g{p}; b{p} = g{p};")
    for _, t in gens:
        chain.append(t)
    chain.extend(tail)
    actions.append(ctx)
    act = " ".join(a for a in actions if a.strip())
    act = f" [ {act} ]" if act else ""
    mn = mnem + ("".join("^" + n for n in names)) + "".join("^" + t for _, t in gens if t.startswith("H"))
    sp = f" {ops}" if ops else ""
    # Sub-constructors without an explicit 'build' are built in reverse operand order; build the
    # general operands in encoding order so that side effects (TOS pops and pushes) happen in order.
    if priv:
        body = ("if (U == 0) goto <priv_ok>;\nns32k_ill_trap();\ngoto <priv_end>;\n<priv_ok>\n" + body.strip() +
                "\n<priv_end>")
    builds = "".join(f"build {t};\n" for _, t in gens if not t.startswith("H"))
    cons.append(f":{mn}{sp} is {' ; '.join(chain)}{act} {{\n{builds}{body.strip()}\n}}")


def con8(mnem, ops, head, body, tail=(), ctx="", priv=False):
    """A constructor without general operands."""
    con(mnem, ops, head, (), tail, body, ctx, priv=priv)


